// One immutable epoch-1 native table set, confined to migration code and historical fixtures.
import { materializeTableSets } from '../../schema/nativeTables'
import type { NeutralTableSet } from '../../schema/neutral'
import { bindDatabaseHandle, databaseHandleContext } from '../../sessionTables'
import type { EngineCapabilities } from '../../capabilities'
import { frozenEpoch1Registry } from './definitions'

export const frozenNativeTableSets = materializeTableSets(frozenEpoch1Registry)
export type FrozenPersistenceTables = NeutralTableSet<typeof frozenEpoch1Registry.tables>
/** Frozen clients keep their own native set; transactions inherit the same handle context. */
export function bindFrozenDatabaseHandle<T extends object>(
  handle: T,
  engine: EngineCapabilities,
): T {
  return bindDatabaseHandle(
    handle,
    frozenNativeTableSets[engine.provider] as unknown as Parameters<typeof bindDatabaseHandle>[1],
    engine,
  )
}
export function frozenTablesOf(handle: object): FrozenPersistenceTables {
  const context = databaseHandleContext(handle)
  const tables = frozenNativeTableSets[context.engine.provider]
  if (context.tables !== (tables as unknown))
    throw new Error('Historical handle has no frozen epoch-1 table binding')
  return tables as FrozenPersistenceTables
}
