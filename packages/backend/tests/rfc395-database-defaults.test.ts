// RFC-395 I-b: native INSERT omission must use database defaults identical to every declared contract column.
import { expect, test } from 'bun:test'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { sql } from 'drizzle-orm'
import { buildLogicalSchemaContract } from '@/bootstrap/persistenceSchema'
import { rawRows } from '@/platform/persistence/queryHelpers'
import { tablesOf } from '@/platform/persistence/sessionTables'
import { describeEachProvider, type ProviderHarness } from './helpers/eachProvider'
import { normalizeSqlText } from './helpers/schemaReconciliation'

// SQLite migration replay keeps the history drift reviewed in RFC-395 I-a
// (`rfc395-provider-catalog-equivalence` locks that ledger exactly); a column default recorded
// there is not a new disagreement. PostgreSQL has no such ledger and stays strict.
const reviewedSqliteDefaults = new Set(
  (
    JSON.parse(
      readFileSync(resolve(import.meta.dir, 'fixtures/rfc395-sqlite-drift.json'), 'utf8'),
    ) as {
      differences: {
        table: string
        kind: string
        replay?: { default?: unknown }
        declared?: { default?: unknown }
      }[]
    }
  ).differences
    .filter(
      (entry) =>
        entry.kind.startsWith('column:') && entry.replay?.default !== entry.declared?.default,
    )
    .map((entry) => `${entry.table}.${entry.kind.slice('column:'.length)}`),
)

const quote = (name: string) => '"' + name.replaceAll('"', '""') + '"'
type DefaultRow = { name: string; expression: string | null; identity: string }
async function defaults(harness: ProviderHarness, table: string): Promise<DefaultRow[]> {
  if (harness.capabilities.isolation === 'exclusive') {
    const rows = await rawRows<{ name: string; expression: string | null }>(
      harness.db,
      sql`select name, dflt_value as expression from pragma_table_info(${table}) order by name`,
    )
    return rows.map((row) => ({
      ...row,
      expression:
        row.expression === null
          ? null
          : normalizeSqlText(row.expression, table)
              .replace(/^TRUE$/i, '1')
              .replace(/^FALSE$/i, '0'),
      identity: '',
    }))
  }
  return await rawRows<DefaultRow>(
    harness.db,
    sql`select a.attname as name, pg_get_expr(d.adbin,d.adrelid) as expression, a.attidentity as identity
    from pg_attribute a join pg_class c on c.oid = a.attrelid join pg_namespace n on n.oid = c.relnamespace
    left join pg_attrdef d on d.adrelid = c.oid and d.adnum = a.attnum
    where n.nspname = 'agent_workflow' and c.relname = ${table} and a.attnum > 0 and not a.attisdropped order by a.attname`,
  )
}

describeEachProvider('RFC-395 I-b database defaults equal contract defaults', (harness) => {
  test('every live column has the same default as a server-canonicalized contract declaration', async () => {
    const contract = buildLogicalSchemaContract()
    const tables = contract.tables.filter((table) => table.disposition !== 'ARCHIVE_THEN_OMIT')
    expect(tables.length).toBeGreaterThan(200)
    const provider = harness.capabilities.provider
    let columnCount = 0
    const mismatches: {
      table: string
      name: string
      expected: DefaultRow | undefined
      actual: DefaultRow
    }[] = []
    for (const [index, table] of tables.entries()) {
      const reference = `rfc395_default_probe_${index}`
      const target =
        provider === 'postgresql' ? `"agent_workflow".${quote(reference)}` : quote(reference)
      const declaration = table.columns
        .map((column) => {
          const type = column.providerType[provider]
          const generated =
            provider === 'postgresql' && column.identity ? ' GENERATED BY DEFAULT AS IDENTITY' : ''
          const expression = column.identity ? null : column.providerDefault[provider]
          return `${quote(column.name)} ${type}${generated}${expression === null ? '' : ` DEFAULT (${expression})`}`
        })
        .join(', ')
      await harness.executeFixtureDdl(`CREATE TABLE ${target} (${declaration})`)
      try {
        const expected = await defaults(harness, reference)
        const actual = await defaults(harness, table.id)
        for (const column of actual) {
          const declared = expected.find((row) => row.name === column.name)
          if (JSON.stringify(column) !== JSON.stringify(declared))
            mismatches.push({
              table: table.id,
              name: column.name,
              expected: declared,
              actual: column,
            })
        }
        expect(actual.length, table.id).toBe(table.columns.length)
        columnCount += actual.length
      } finally {
        await harness.executeFixtureDdl(`DROP TABLE ${target}`)
      }
    }
    expect(
      mismatches.filter(
        (mismatch) =>
          provider !== 'sqlite' ||
          !reviewedSqliteDefaults.has(`${mismatch.table}.${mismatch.name}`),
      ),
    ).toEqual([])
    expect(columnCount).toBe(tables.reduce((count, table) => count + table.columns.length, 0))
  }, 180_000)

  test('native omitted values and explicitly provided null retain distinct meanings', async () => {
    const { agents } = tablesOf(harness.db)
    const [row] = await harness.db
      .insert(agents)
      .values({ id: 'rfc395_defaults', name: 'defaults', ownerUserId: null })
      .returning()
    expect(row?.syncOutputsOnIterate).toBe(true)
    expect(row?.ownerUserId).toBeNull()
    expect(row?.createdAt).toBeGreaterThan(0)
    expect(typeof row?.createdAt).toBe('number')
  })
})
