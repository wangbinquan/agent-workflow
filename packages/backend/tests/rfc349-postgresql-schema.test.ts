// RFC-349 T4/T8 — locks the independent PostgreSQL baseline: 216 active
// tables, six archive-only omissions, native provider types/defaults, and no
// replay of SQLite migration SQL.

import { describe, expect, test } from 'bun:test'
import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { loadPostgresqlMigrationHistory } from '@/platform/persistence/migration/legacy/postgresqlMigrationHistory'
import {
  buildPostgresqlSchemaPlan,
  renderPostgresqlBaselineSql,
} from '@/platform/persistence/migration/legacy/postgresqlSchema'
import {
  canonicalSchemaJson,
  RFC349_ARCHIVE_THEN_OMIT_TABLES,
} from '@/platform/persistence/schemaContract'
import { buildFrozenEpoch1LogicalSchemaContract as buildLogicalSchemaContract } from '@/platform/persistence/migration/epoch1/contract'

describe('RFC-349 PostgreSQL schema projection', () => {
  test('projects the exact active parity set', () => {
    const contract = buildLogicalSchemaContract()
    const plan = buildPostgresqlSchemaPlan(contract)
    const tables = plan.statements.filter((statement) => statement.kind === 'table')
    // RFC-371 v2 retired 81 v1 observation tables and added the three call / model / price tables;
    // RFC-370 v2 retired the host write-context and memory distill receipt tables; RFC-370 M0
    // added the hosted configuration document, external identity and skill content tables; RFC-370
    // M1 added the hosted execution control, binding and task workspace tables; RFC-370 v3 V11
    // squashed every unreleased hosted table into one 0035 migration.
    expect(tables).toHaveLength(216)
    expect(tables.some((table) => table.logicalId === 'task_execution_observation_sources')).toBe(
      false,
    )
    expect(tables.some((table) => table.logicalId === 'observation_calls')).toBe(true)
    expect(new Set(tables.map((statement) => statement.logicalId)).size).toBe(216)
    expect(
      tables
        .map((statement) => statement.logicalId)
        .filter((id) => id.startsWith('task_clarify_'))
        .sort(),
    ).toEqual([])
    // RFC-372 lightweight mode retires the ten independent companion tables.
    expect(
      tables
        .map((statement) => statement.logicalId)
        .filter((id) => id.startsWith('clarify_mindmap_'))
        .sort(),
    ).toEqual([])
    // RFC-371 v2 (PostgreSQL 0032): the three call / model / price tables are the whole
    // observation store; no v1 projection, report, native-usage or system source table remains.
    const ids = tables.map((statement) => statement.logicalId)
    expect(ids.filter((id) => /^observation_|native_usage|_observation_/.test(id)).sort()).toEqual([
      'observation_call_models',
      'observation_calls',
      'observation_prices',
    ])
    expect(ids.filter((id) => id.startsWith('system_agent_'))).toEqual([])
    // RFC-396: the same five design tables participate in native PostgreSQL.
    expect(ids.filter((id) => id.startsWith('development_design')).sort()).toEqual([
      'development_design_baselines',
      'development_design_links',
      'development_design_proposals',
      'development_design_revisions',
      'development_designs',
    ])
    expect(plan.activeTableCount).toBe(contract.activeTableCount)
    expect(plan.archiveOnlyTableCount).toBe(6)
  })

  test('omits exactly the six approved legacy tables', () => {
    const sql = renderPostgresqlBaselineSql(buildPostgresqlSchemaPlan(buildLogicalSchemaContract()))
    for (const table of RFC349_ARCHIVE_THEN_OMIT_TABLES) {
      expect(sql).not.toContain(`CREATE TABLE "agent_workflow"."${table}"`)
    }
    expect(sql).toContain('CREATE TABLE "agent_workflow"."tasks"')
    expect(sql).toContain('CREATE TABLE "agent_workflow"."code_work_items"')
  })

  test('uses PostgreSQL-native boolean, bigint, identity and defaults', () => {
    const sql = renderPostgresqlBaselineSql(buildPostgresqlSchemaPlan(buildLogicalSchemaContract()))
    expect(sql).toContain('"sync_outputs_on_iterate" BOOLEAN NOT NULL DEFAULT TRUE')
    expect(sql).toContain('"created_at" BIGINT NOT NULL DEFAULT (extract(epoch')
    expect(sql).toContain('"id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL')
    expect(sql).toContain('DEFAULT md5(random()::text || clock_timestamp()::text)')
  })

  test('maps SQLite-only check syntax and bounds physical identifiers', () => {
    const plan = buildPostgresqlSchemaPlan(buildLogicalSchemaContract())
    const sql = renderPostgresqlBaselineSql(plan)
    expect(sql).not.toMatch(/\bGLOB\b/i)
    expect(sql).not.toMatch(/\brandomblob\s*\(/i)
    expect(sql).toContain("!~ '[^0-9a-f]'")
    expect(sql).toContain('"from_scope_id" IS DISTINCT FROM "to_scope_id"')
    expect(sql).toContain('"reset_pending" IN (FALSE, TRUE)')
    for (const statement of plan.statements.filter(
      (candidate) => candidate.kind === 'constraint' || candidate.kind === 'index',
    )) {
      const identifier = /(?:CONSTRAINT|INDEX) "([^"]+)"/.exec(statement.sql)?.[1]
      expect(identifier).toBeDefined()
      expect(Buffer.byteLength(identifier!, 'utf8')).toBeLessThanOrEqual(63)
    }
  })

  test('plan digest is deterministic and covers every DDL statement', () => {
    const first = buildPostgresqlSchemaPlan(buildLogicalSchemaContract())
    const second = buildPostgresqlSchemaPlan(buildLogicalSchemaContract())
    expect(first).toEqual(second)
    expect(first.digest).toMatch(/^sha256:[a-f0-9]{64}$/)
    const { digest: _digest, ...payload } = first
    expect(first.digest).toBe(
      `sha256:${createHash('sha256').update(canonicalSchemaJson(payload)).digest('hex')}`,
    )
    const mutated = {
      ...payload,
      statements: first.statements.map((statement, index) =>
        index === 0 ? { ...statement, sql: `${statement.sql} ` } : statement,
      ),
    }
    expect(first.digest).not.toBe(
      `sha256:${createHash('sha256').update(canonicalSchemaJson(mutated)).digest('hex')}`,
    )
  })

  test('committed immutable baseline and journal match the current projector', async () => {
    const currentPlan = buildPostgresqlSchemaPlan(buildLogicalSchemaContract())
    const history = await loadPostgresqlMigrationHistory({
      headContract: buildLogicalSchemaContract(),
    })
    // The original byte/journal oracles still bind the immutable baseline;
    // replaying its verified append-only history must reach today's projector.
    const plan = history.root.plan
    const migrationRoot = resolve(import.meta.dir, '..', 'db', 'postgresql-migrations')
    expect(readFileSync(resolve(migrationRoot, '0000_rfc349_baseline.sql'), 'utf8')).toBe(
      renderPostgresqlBaselineSql(plan),
    )
    const journal = JSON.parse(
      readFileSync(resolve(migrationRoot, 'meta', '_journal.json'), 'utf8'),
    ) as {
      baselineId: string
      contractDigest: string
      planDigest: string
      statements: readonly { digest: string }[]
    }
    expect(journal.baselineId).toBe(plan.baselineId)
    expect(journal.contractDigest).toBe(plan.contractDigest)
    expect(journal.planDigest).toBe(plan.digest)
    expect(journal.statements).toHaveLength(plan.statements.length)
    expect(journal.statements.map((statement) => statement.digest)).toEqual(
      plan.statements.map(
        (statement) => `sha256:${createHash('sha256').update(statement.sql).digest('hex')}`,
      ),
    )
    expect(history.head.plan).toEqual(currentPlan)
    expect(history.head.contract).toEqual(buildLogicalSchemaContract())
    expect(history.steps.at(-1)?.id).toBe('0038_epoch1_permission_text')
    expect(history.steps).toHaveLength(38)
    expect(history.head.sqliteMigrations).toHaveLength(262)
  })
})
