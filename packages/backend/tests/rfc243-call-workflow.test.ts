// RFC-243 PR-3 — call-workflow 节点端到端（design §6.2 D→L→W→F→M 全链）。
//
// Locks in:
//   1. 父任务的 call 节点从冻结闭包起独立子任务：子任务行 parentTaskId /
//      parentNodeRunId / invocationDepth=1 / spaceKind='inherited'，其 canonical
//      即调用行的 iso worktree。
//   2. 工作区继承（D5）：父 canonical 的【未提交】文件对子任务的 agent 可见
//      （通过 iso 派生 —— snapshotFullState 含未提交/untracked）。
//   3. 子任务 done → F 输出回填（call 行 node_run_outputs = 子任务 output 投影）
//      → M 合并回（子任务写盘文件落回父 canonical）→ 调用行 done+merged →
//      父 output 节点消费 call 端口 → 父任务 done。
//   4. 子任务失败 → 调用行 failed(child-task-failed) → 父任务 failed（错误
//      摘要携带子任务信息）。
//   5. freezeCallClosure 纯服务：无 call 节点 → null；引用缺失 →
//      workflow-call-ref-missing；A→B→A → workflow-call-cycle（id-only 载荷）。
