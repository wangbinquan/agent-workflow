interface Seeded {
  parentTaskId: string
  childWorkflowId: string
}

async function seedParentTask(h: Harness, workerId: string): Promise<Seeded> {
  const childDef = childDefinition(workerId)
  const childWorkflowId = ulid()
  await h.db.insert(workflows).values({
    id: childWorkflowId,
    name: 'child-wf',
    definition: JSON.stringify(childDef),
  })
  const parentDef = parentDefinition()
  const parentWorkflowId = ulid()
  await h.db.insert(workflows).values({
    id: parentWorkflowId,
    name: 'parent-wf',
    definition: JSON.stringify(parentDef),
  })
  const closure = JSON.stringify({
    workflows: { 'child-wf': { id: childWorkflowId, version: 1, definition: childDef } },
  })
  const parentTaskId = ulid()
  await h.db.insert(tasks).values({
    id: parentTaskId,
    name: 'rfc243-parent',
    workflowId: parentWorkflowId,
    workflowSnapshot: JSON.stringify(parentDef),
    repoPath: h.repoPath,
    worktreePath: h.worktreePath,
    baseBranch: 'main',
    branch: `agent-workflow/${parentTaskId}`,
    status: 'pending',
    inputs: JSON.stringify({ req: 'go' }),
    startedAt: Date.now(),
    refClosureJson: closure,
  })
  return { parentTaskId, childWorkflowId }
}

describe('RFC-243 e2e — call-workflow 全链', () => {
  let h: Harness
  beforeEach(async () => {
    h = await buildHarness()
  })
  afterEach(() => h?.cleanup())

  test('D→L→W→F→M：继承派生、子任务独立行、输出回填、合并回父、父任务 done', async () => {
    const workerId = await seedAgent(h.db, 'worker', ['out', 'echo'])
    // 父 canonical 的未提交文件 —— 子 agent 用 __FILE__ 读它证明继承可见。
    writeFileSync(join(h.worktreePath, 'parent-seed.txt'), 'UNCOMMITTED PARENT STATE')
    writeFileSync(
      h.planFile,
      JSON.stringify({
        worker: {
          files: { 'src/child-artifact.txt': 'WRITTEN BY CHILD' },
          output: { out: 'CHILD SAYS HI', echo: '__FILE__:parent-seed.txt' },
        },
      }),
    )
    const { parentTaskId } = await seedParentTask(h, workerId)
    await runTask({
      db: h.db,
      taskId: parentTaskId,
      appHome: h.appHome,
      binaryOverride: ['bun', 'run', h.mockPath],
    })

    const parent = (await h.db.select().from(tasks).where(eq(tasks.id, parentTaskId)))[0]!
    expect(parent.status).toBe('done')

    // 子任务独立行：父链接 + inherited 空间 + done。
    const children = await h.db.select().from(tasks).where(eq(tasks.parentTaskId, parentTaskId))
    expect(children.length).toBe(1)
    const child = children[0]!
    expect(child.status).toBe('done')
    expect(child.spaceKind).toBe('inherited')
    expect(child.invocationDepth).toBe(1)
    expect(child.name).toContain('rfc243-parent')

    // 调用行：childTaskId / done / merged / 输出回填（F）。
    const callRow = (
      await h.db
        .select()
        .from(nodeRuns)
        .where(and(eq(nodeRuns.taskId, parentTaskId), eq(nodeRuns.nodeId, 'call1')))
    ).find((r) => r.parentNodeRunId === null)!
    expect(callRow.childTaskId).toBe(child.id)
    expect(callRow.status).toBe('done')
    expect(callRow.mergeState).toBe('merged')
    expect(child.parentNodeRunId).toBe(callRow.id)
    const callOutputs = await h.db
      .select()
      .from(nodeRunOutputs)
      .where(eq(nodeRunOutputs.nodeRunId, callRow.id))
    const byPort = new Map(callOutputs.map((o) => [o.portName, o.content]))
    expect(byPort.get('report')).toBe('CHILD SAYS HI')
    // D5 继承：子 agent 在自己的工作区读到了父 canonical 的未提交文件。
    expect(byPort.get('echo')).toBe('UNCOMMITTED PARENT STATE')

    // M 合并回：子任务写盘的文件出现在父 canonical。
    const merged = join(h.worktreePath, 'src', 'child-artifact.txt')
    expect(existsSync(merged)).toBe(true)
    expect(readFileSync(merged, 'utf8')).toBe('WRITTEN BY CHILD')

    // 父 output 节点消费 call 端口。
    const outRow = (
      await h.db
        .select()
        .from(nodeRuns)
        .where(and(eq(nodeRuns.taskId, parentTaskId), eq(nodeRuns.nodeId, 'pout')))
    )[0]!
    const outPorts = await h.db
      .select()
      .from(nodeRunOutputs)
      .where(eq(nodeRunOutputs.nodeRunId, outRow.id))
    expect(outPorts.find((o) => o.portName === 'report')?.content).toBe('CHILD SAYS HI')
  })

  test('RFC-292: child task atomically inherits nested context and expands it in child agent prompt', async () => {
    const workerId = await seedAgent(h.db, 'worker', ['out', 'echo'])
    writeFileSync(
      h.planFile,
      JSON.stringify({ worker: { output: { out: 'CHILD', echo: 'context' } } }),
    )
    const { parentTaskId } = await seedParentTask(h, workerId)
    const parent = (await h.db.select().from(tasks).where(eq(tasks.id, parentTaskId)))[0]!
    const closure = JSON.parse(parent.refClosureJson!) as {
      workflows: Record<
        string,
        { definition: { $schema_version: number; nodes: Array<Record<string, unknown>> } }
      >
    }
    const child = closure.workflows['child-wf']!.definition
    child.$schema_version = 5
    const worker = child.nodes.find((node) => node.id === 'work')!
    worker.promptTemplate = 'do {{req}} / {{trigger.webhook.comment_text}}'
    const context = {
      trigger: {
        webhook: {
          event_type: 'note',
          comment_text: 'child-inherited-trigger',
        },
      },
    }
    await h.db
      .update(tasks)
      .set({
        refClosureJson: JSON.stringify(closure),
        triggerContextJson: JSON.stringify(context),
      })
      .where(eq(tasks.id, parentTaskId))

    await runTask({
      db: h.db,
      taskId: parentTaskId,
      appHome: h.appHome,
      binaryOverride: ['bun', 'run', h.mockPath],
    })

    const childTask = (
      await h.db.select().from(tasks).where(eq(tasks.parentTaskId, parentTaskId))
    )[0]!
    expect(JSON.parse(childTask.triggerContextJson!)).toEqual(context)
    const childRun = (
      await h.db
        .select()
        .from(nodeRuns)
        .where(and(eq(nodeRuns.taskId, childTask.id), eq(nodeRuns.nodeId, 'work')))
    )[0]!
    expect(childRun.promptText).toContain('child-inherited-trigger')
    expect(childRun.promptText).not.toContain('{{trigger.webhook.comment_text}}')
  })

  test('子任务失败 → 调用行 failed(child-task-failed) → 父任务 failed', async () => {
    const workerId = await seedAgent(h.db, 'worker', ['out', 'echo'])
    writeFileSync(h.planFile, JSON.stringify({ worker: { exitCode: 3 } }))
    const { parentTaskId } = await seedParentTask(h, workerId)
    await runTask({
      db: h.db,
      taskId: parentTaskId,
      appHome: h.appHome,
      binaryOverride: ['bun', 'run', h.mockPath],
      // 子任务 agent 重试烧时间——压到 0 让失败立即冒泡。
      defaultNodeRetries: 0,
    })
    const parent = (await h.db.select().from(tasks).where(eq(tasks.id, parentTaskId)))[0]!
    expect(parent.status).toBe('failed')
    const children = await h.db.select().from(tasks).where(eq(tasks.parentTaskId, parentTaskId))
    expect(children.length).toBe(1)
    expect(children[0]!.status).toBe('failed')
    const callRow = (
      await h.db
        .select()
        .from(nodeRuns)
        .where(and(eq(nodeRuns.taskId, parentTaskId), eq(nodeRuns.nodeId, 'call1')))
    ).find((r) => r.parentNodeRunId === null)!
    expect(callRow.status).toBe('failed')
    expect(callRow.failureCode).toBe('child-task-failed')
  })
})

describe('RFC-243 e2e — 生命周期', () => {
  let h: Harness
  beforeEach(async () => {
    h = await buildHarness()
  })
  afterEach(() => h?.cleanup())

  test('mid-flight 取消父任务：级联取消子任务并落 durable 标记，调用行 canceled', async () => {
    const workerId = await seedAgent(h.db, 'worker', ['out', 'echo'])
    // worker 挂起：hang 计划项让子任务停在 running。
    writeFileSync(h.planFile, JSON.stringify({ worker: { hangMs: 120000 } }))
    const { parentTaskId } = await seedParentTask(h, workerId)
    const { cancelTask } = await import('../src/services/task')
    const running = runTask({
      db: h.db,
      taskId: parentTaskId,
      appHome: h.appHome,
      binaryOverride: ['bun', 'run', h.mockPath],
    })
    // 等到子任务出现且 running（budget→iso→launch 全链完成）。
    let childId: string | null = null
    for (let i = 0; i < 200 && childId === null; i++) {
      const rows = await h.db.select().from(tasks).where(eq(tasks.parentTaskId, parentTaskId))
      if (rows[0]?.status === 'running') childId = rows[0].id
      else await Bun.sleep(50)
    }
    expect(childId).not.toBeNull()
    await cancelTask(h.db, parentTaskId)
    await running
    const parent = (await h.db.select().from(tasks).where(eq(tasks.id, parentTaskId)))[0]!
    const child = (await h.db.select().from(tasks).where(eq(tasks.id, childId!)))[0]!
    expect(parent.status).toBe('canceled')
    expect(child.status).toBe('canceled')
    expect(child.errorMessage).toBe('canceled-by-parent-cascade')
    const callRow = (
      await h.db
        .select()
        .from(nodeRuns)
        .where(and(eq(nodeRuns.taskId, parentTaskId), eq(nodeRuns.nodeId, 'call1')))
    ).find((r) => r.parentNodeRunId === null)!
    expect(['canceled', 'failed']).toContain(callRow.status)
  }, 30000)

  test('重试调用节点：旧子任务保留为历史行，新子任务全新发起并成功', async () => {
    const workerId = await seedAgent(h.db, 'worker', ['out', 'echo'])
    writeFileSync(h.planFile, JSON.stringify({ worker: { exitCode: 3 } }))
    const { parentTaskId } = await seedParentTask(h, workerId)
    await runTask({
      db: h.db,
      taskId: parentTaskId,
      appHome: h.appHome,
      binaryOverride: ['bun', 'run', h.mockPath],
      defaultNodeRetries: 0,
    })
    const failedCall = (
      await h.db
        .select()
        .from(nodeRuns)
        .where(and(eq(nodeRuns.taskId, parentTaskId), eq(nodeRuns.nodeId, 'call1')))
    ).find((r) => r.parentNodeRunId === null)!
    expect(failedCall.status).toBe('failed')
    // 修好计划 → retryNode 换代。
    writeFileSync(
      h.planFile,
      JSON.stringify({ worker: { output: { out: 'SECOND TRY', echo: 'x' } } }),
    )
    const { retryNode } = await import('../src/services/task')
    await retryNode(h.db, parentTaskId, failedCall.id, {
      deps: {
        db: h.db,
        appHome: h.appHome,
        binaryOverride: ['bun', 'run', h.mockPath],
      } as unknown as StartTaskDeps,
    })
    // retryNode 的 kick 是 fire-and-forget —— 轮询到终态再断言。
    let parent = (await h.db.select().from(tasks).where(eq(tasks.id, parentTaskId)))[0]!
    for (let i = 0; i < 300 && !['done', 'failed', 'canceled'].includes(parent.status); i++) {
      await Bun.sleep(50)
      parent = (await h.db.select().from(tasks).where(eq(tasks.id, parentTaskId)))[0]!
    }
    expect(parent.status).toBe('done')
    const children = await h.db.select().from(tasks).where(eq(tasks.parentTaskId, parentTaskId))
    expect(children.length).toBe(2) // 旧 failed 历史行 + 新 done
    expect(children.map((c) => c.status).sort()).toEqual(['done', 'failed'])
  }, 30000)
})

