-- RFC-248 AC-19 —— 只读成员被改动的可见化。
--
-- D11 规定只读成员不快照、不进 diff、不自动提交推送。但框架**不在文件系统层面
-- 阻止写入**——agent 完全可能改了它。静默丢弃这些改动是最难排查的一类问题：
-- 用户看到 agent 说「我改好了」，工作树里也确实改了，但推上去什么都没有。
--
-- 之前只落了一条 `log.warn`，日志翻不到就等于没有。这里加一列持久化计数，让
-- 任务详情能在那个只读成员旁边显示「有 N 处改动被丢弃」。
--
-- **为什么不复用 `lifecycle_alerts`**：那张表绑的是 `LifecycleAlertRule` 枚举，
-- RFC-108 的自动修复循环会全局扫描并尝试**修复**其中的每一条。而「只读仓被改
-- 动了」不是一个待修复的不变量违反——它是一条给人看的事实通报，让修复循环去
-- 碰它只会造成误修。
--
-- NULL = 从未检查过（存量行 / 可写成员）；0 = 检查过且干净；N>0 = 丢弃了 N 处。

ALTER TABLE task_repos ADD COLUMN readonly_dirty_count INTEGER;
