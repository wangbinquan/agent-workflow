-- RFC-311 T21 —— `node_runs.prompt_text` 外置到文件。
--
-- 审计实测：`node_runs` 平均每行 ~10.5KB，其中 **prompt_text 平均 ~6KB、占该表
-- 57%**。它把每一次「按 node_run 取行」的代价都抬高了——SQLite 把超出页大小的
-- 部分放进溢出页链，任何 `SELECT *`（历史上审计逐条列出的那些全列读）都要跟着
-- 读溢出页；而这段文本的读点只有详情页与会话视图，属于**点开才看**的内容。
--
-- 做法（design §7.2）：新增 `prompt_path`，**新行写文件、旧行不回填**，读点双读
-- （列有值用列，否则读文件）。不回填的理由是回填要为几万行各写一个文件、且旧行
-- 的价值随时间衰减；双读让两种形态永久共存，没有切换窗口。
ALTER TABLE `node_runs` ADD `prompt_path` text;
